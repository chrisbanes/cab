export function assertProjectDeletionInventory(db: Database): void {
  const actual = db
    .prepare(
      "SELECT name FROM sqlite_schema WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    )
    .all()
    .map((row) => String((row as { name: unknown }).name));
  const expected = Object.keys(projectDeletionInventory).sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected))
    throw new Error("Project deletion schema inventory is unavailable");
  for (const table of expected) {
    const columns = db
      .prepare(`PRAGMA table_info(${table})`)
      .all()
      .map((row) => String((row as { name: unknown }).name));
    const classified =
      projectDeletionInventory[table as keyof typeof projectDeletionInventory]
        .columns;
    if (JSON.stringify(columns) !== JSON.stringify(classified))
      throw new Error("Project deletion column inventory is unavailable");
  }
}
